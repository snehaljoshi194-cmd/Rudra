export function getAchievementById(id: string | null): AchievementDefinition | null {
  if (!id) return null;
  return ACHIEVEMENTS.find((a) => a.id === id) || null;
}

export function getClaimableAchievementCount(save: SaveData): number {
  return ACHIEVEMENTS.filter(
    (a) => a.getProgress(save) >= a.target && !save.claimedAchievements.includes(a.id)
  ).length;
}
